/**
 * Writes the SQL that seeds the single admin user.
 *
 *   npm run db:seed-admin -- hola@thexify.com "a-long-real-password"
 *
 * It does not touch the database: it writes seed-admin.sql (gitignored), applied
 * with `wrangler d1 execute --file`. PowerShell breaks on the `$2b$` of a bcrypt
 * hash when it is pasted inline (documented in the vault).
 */
import bcrypt from 'bcryptjs';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';

let [, , email, password, name = 'Matheo Flores'] = process.argv;

// Avoid putting production credentials in shell history or process arguments.
// Populate these temporary variables from the shell's secure-input facility.
if (email === '--env') {
  email = process.env.THEXIFY_ADMIN_EMAIL?.trim();
  password = process.env.THEXIFY_ADMIN_PASSWORD;
  name = process.env.THEXIFY_ADMIN_NAME?.trim() || name;
}

if (!email || !password) {
  console.error('Uso: npm run db:seed-admin -- <correo> <contraseña> [nombre]');
  console.error('Seguro: usa variables temporales y ejecuta `node scripts/seed-admin.mjs --env`.');
  process.exit(1);
}
if (password.length < 12) {
  console.error('La contraseña tiene menos de 12 caracteres. Usa una real: es la llave del panel.');
  process.exit(1);
}

const hash = await bcrypt.hash(password, 10);
const escape = (value) => value.replace(/'/g, "''");
const sql = `-- Generated by scripts/seed-admin.mjs. Do not commit. Replaces the user if the email exists.
INSERT INTO users (email, password_hash, name, role, created_at)
VALUES ('${escape(email.toLowerCase())}', '${escape(hash)}', '${escape(name)}', 'admin', CURRENT_TIMESTAMP)
ON CONFLICT(email) DO UPDATE SET password_hash = excluded.password_hash, name = excluded.name;
`;

const target = path.join(process.cwd(), 'seed-admin.sql');
await writeFile(target, sql, 'utf8');

console.log(`✓ ${target}\n`);
console.log('Aplícalo con:');
console.log('  npx wrangler d1 execute thexify-db --local  --file=seed-admin.sql');
console.log('  npx wrangler d1 execute thexify-db --remote --file=seed-admin.sql\n');
console.log('Y después borra seed-admin.sql.');
